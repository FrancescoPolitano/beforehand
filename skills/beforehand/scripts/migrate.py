#!/usr/bin/env python3
"""Bring a store written for an older schema up to the current one, with the diff first.

Why this exists (FR-7.3). Until now a schema change was a habit, not a version: watchlist
ids were assigned by a command someone had to remember to run, the Italian empty-section
form was recognised by whichever script happened to hardcode it, and the AUDIT header still
called a hand-appended file derived data. Nothing recorded which shape a given store was
written in, so nothing could tell a store that predates a rule from a store that breaks it.
`schema:` on personas and on `context.md` is that record; this command is the only thing
that moves it, and it moves the file's shape with it.

What the 0.1 -> 0.2 migration does, per file:
  persona (`personas/*.md`)  `schema: 0.2` added to the frontmatter; Watchlist bullets
                             numbered `[wl-NN]` (the same numbering `watchlist --assign-ids`
                             does, from the same function); a joined Fact tag split into one
                             parenthesis per Fact, but only where each segment carries
                             exactly one path-like field, so the split cannot guess which
                             source belongs to which claim; a declared-empty bullet written in
                             any form the loaded locale recognises rewritten to the canonical
                             English one (FR-4.4) — only when the WHOLE bullet is the phrase
                             plus a date. A bullet that carries the phrase inside other words
                             (a sentence, a Fact tag) is left exactly as written and listed on
                             a `left as prose:` line: rewriting it would drop what it says.
  `context.md`               `schema: 0.2` added to the frontmatter.
  `AUDIT.md`                 the derived-file header replaced by the hand-appended wording
                             (FR-3.5) and the schema comment added.
  snapshots                  an existing `schema:` line bumped. A snapshot that never had one
                             predates the field and keeps not having one: adding it would
                             change how `pending` counts its predictions. A snapshot with no
                             `schema:` and no ledger sections is a pre-0.2 prose snapshot: it
                             is never rewritten here (only its id and title could be parsed
                             out of a prose prediction; the slug, grounding, specificity and
                             dates are judgment) — grade it through `calibrate --ledger`.
  `INDEX.md`                 not edited here — regenerated by the reindex that follows.

Nothing is written without `--apply`: what is printed is the unified diff of every file that
would change, because a persona is the user's file and a migration is still an edit.

The guard. Before anything is written, every proposed file is compared with the one on disk
through `verify_quotes.content_loss` — the `--against` rule. A migration that would reduce
Fact tags or headings is refused for the whole run (exit 2) and nothing is written.

Usage:
  migrate.py [--store ~/.beforehand] [--context NAME] [--to 0.2] [--apply]

Exit codes: 0 ok · 1 usage · 2 the migration would lose content (refused)
"""
import sys

sys.dont_write_bytecode = True  # before any sibling import (G5)

import argparse  # noqa: E402
import datetime as dt  # noqa: E402
import difflib  # noqa: E402
import re  # noqa: E402
from pathlib import Path  # noqa: E402

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS))
import reindex  # noqa: E402
import watchlist  # noqa: E402
from personas_lib import (  # noqa: E402
    FACT_LABEL_RE,
    PATHLIKE_RE,
    QUOTE_RE,
    SCHEMA_VERSION,
    Store,
    atomic_write,
    check_locale,
    frontmatter_span,
    get_locale,
    locale_regexes,
    paren_groups,
    read_text_lenient,
    rel,
    resolve_store,
    schema_of,
    split_top_level,
    unquote_ref,
)
from verify_quotes import content_loss  # noqa: E402

# A hook, not a bare call: the tests pin the date without asserting on today (global
# constraint "never assert on today's date").
_today = dt.date.today

AUDIT_HEADER = "<!-- one line per source ingestion; hand-appended -->"
SCHEMA_COMMENT = "<!-- schema: %s -->" % SCHEMA_VERSION
# The head of an AUDIT.md written at the current schema: what `migrate_audit` produces, so a
# file started from it is already migrated. `forget` creates a missing AUDIT from this one
# constant (E3): a bare `# AUDIT` made the next migrate show a diff on a 0.2 store.
AUDIT_TEMPLATE = "# AUDIT\n\n%s\n%s\n" % (AUDIT_HEADER, SCHEMA_COMMENT)
# How `personas_lib.parse_tags` separates the segments of a joined tag (FR-2.2); the split
# below must cut exactly where the parser sees a boundary, so the rule is the same regex.
JOIN_SPLIT_RE = re.compile(r";\s*(?=Fact\b)")
_HEADER_COMMENT_RE = re.compile(r"^<!--.*(derived|hand-edit|hand-appended|ingestion|schema:)",
                                re.I)


# --------------------------------------------------------------------------- per-file rules
def set_schema(text, version=SCHEMA_VERSION):
    """`schema: <version>` in the frontmatter block: replaced in place if present, otherwise
    added as the last key, where the template keeps it."""
    span = frontmatter_span(text)
    if not span:
        return text                     # no frontmatter: not a file this migration owns
    block, rest = text[span[0]:span[1]], text[span[1]:]
    lines = block.split("\n")
    for i, line in enumerate(lines):
        if re.match(r"^schema:", line):         # `schema:0.1` too (E9)
            if line.strip() == "schema: %s" % version:
                return text
            lines[i] = "schema: %s" % version
            return "\n".join(lines) + rest
    close = max(i for i, line in enumerate(lines) if line.rstrip() == "---")
    lines.insert(close, "schema: %s" % version)
    return "\n".join(lines) + rest


def assign_watchlist_ids(text):
    """The `watchlist --assign-ids` numbering, run in process (never a subprocess: the two
    must agree by construction, not by two copies of the same loop)."""
    if watchlist.watchlist_span(text) is None:
        return text
    return watchlist.assign_ids(text)[0]


def _path_fields(segment):
    """The path-like fields of one tag segment, counted the way the parser counts them."""
    fields = split_top_level(QUOTE_RE.sub('""', segment))
    return [f for f in fields if PATHLIKE_RE.search(unquote_ref(f))]


def split_joined_tags(text):
    """One parenthesis per Fact (FR-2.2), where the split is unambiguous.

    Unambiguous means: every segment of the joined group carries exactly one path-like field.
    A segment with none inherits its source from a neighbour (the `same source` shorthand),
    and a segment with two has a reference the parser itself would have to choose between —
    in both cases splitting would assign evidence to a claim on a guess, so the group is left
    exactly as written and `lint` keeps reporting it as joined.
    """
    out = text
    for start, end, inner in reversed(list(paren_groups(text))):
        if not FACT_LABEL_RE.search(inner):
            continue
        segments = JOIN_SPLIT_RE.split(inner)
        if len(segments) < 2:
            continue
        if any(len(_path_fields(s)) != 1 for s in segments):
            continue
        out = out[:start] + "(" + ") (".join(s.strip() for s in segments) + ")" + out[end:]
    return out


def _empty_bullets(text):
    """-> [(index, line, whole)] for every bullet carrying a recognised declared-empty phrase;
    `whole` is True when the bullet IS the phrase plus a date and nothing else (FR-5.4)."""
    empty_re = locale_regexes()["empty_decl_re"]
    out = []
    for i, line in enumerate(text.split("\n")):
        if not line.lstrip().startswith("- ") or not empty_re.search(line):
            continue
        out.append((i, line, empty_re.fullmatch(line.strip()[2:].strip()) is not None))
    return out


def canonical_empty_sections(text):
    """A declared-empty bullet in any recognised form -> the canonical English one (FR-4.4).

    The canonical phrase is read from the built-in English locale rather than spelled here,
    so the form the scripts write stays defined in one file. Only a bullet that is the phrase
    plus a date and nothing else is rewritten (`fullmatch`, E6): the old `search` turned a
    sentence that merely contained the phrase into the bare canonical bullet, and the content
    guard counts Fact tags, headings and bytes — it could not see the lost words. Every other
    bullet carrying the phrase is left for `prose_empty_bullets` to report.
    """
    canonical = get_locale("en")["empty_section"][0]
    lines = text.split("\n")
    for i, line, whole in _empty_bullets(text):
        if not whole:
            continue
        date = re.search(r"\d{4}-\d{2}-\d{2}", line).group(0)
        indent = line[:len(line) - len(line.lstrip())]
        lines[i] = "%s- %s %s" % (indent, canonical, date)
    return "\n".join(lines)


def prose_empty_bullets(text):
    """-> [(line number, bullet)] the declared-empty rule left alone because the bullet says
    more than the phrase and a date (reported on `left as prose:` lines)."""
    return [(i + 1, line.strip()) for i, line, whole in _empty_bullets(text) if not whole]


def migrate_persona(text):
    for step in (set_schema, assign_watchlist_ids, split_joined_tags, canonical_empty_sections):
        text = step(text)
    return text


def migrate_context_md(text):
    return set_schema(text)


def migrate_snapshot(text):
    """Only an existing `schema:` line is bumped (see the module docstring)."""
    if not re.search(r"(?m)^schema:", text):   # `schema:0.1` too (E9)
        return text
    new = re.sub(r"(?m)^schema:[ \t]*\S+[ \t]*$", "schema: %s" % SCHEMA_VERSION, text, count=1)
    return new


def migrate_audit(text):
    """The header of a hand-appended file (FR-3.5), plus the schema comment (FR-7.3).

    Header comments are rewritten rather than appended to: a 0.1 AUDIT carries a derived-file
    marker, which is the statement being corrected, and leaving it next to its correction
    would leave the file saying both.
    """
    lines = text.split("\n")
    head_len = min(len(lines), 8)
    keep = [ln for i, ln in enumerate(lines)
            if not (i < head_len and _HEADER_COMMENT_RE.match(ln.strip()))]
    title_idx = next((i for i, ln in enumerate(keep[:3]) if ln.startswith("# ")), None)
    if title_idx is None:
        rest = keep
        head = []
    else:
        head = keep[:title_idx + 1]
        rest = keep[title_idx + 1:]
    while rest and not rest[0].strip():
        rest.pop(0)
    return "\n".join(head + [""] + [AUDIT_HEADER, SCHEMA_COMMENT, ""] + rest)


# --------------------------------------------------------------------------- the run
def planned_changes(ctx):
    """-> [(path, old_text, new_text)] for one context directory, in reading order."""
    plan = []
    candidates = [(ctx / "context.md", migrate_context_md)]
    candidates += [(p, migrate_persona) for p in sorted((ctx / "personas").glob("*.md"))
                   if (ctx / "personas").is_dir()]
    candidates.append((ctx / "AUDIT.md", migrate_audit))
    cal = ctx / "calibration"
    if cal.is_dir():
        candidates += [(p, migrate_snapshot)
                       for p in sorted(list(cal.glob("pending-*.md")) + list(cal.glob("done-*.md")))]
    for path, rule in candidates:
        if not path.is_file():
            continue
        old = read_text_lenient(path)
        new = rule(old)
        if new != old:
            plan.append((path, old, new))
    return plan


def from_version(ctx):
    """The version a context is migrated FROM, for the AUDIT line: what its files declare,
    or 0.1 when they declare nothing (the release that had no `schema:` on personas)."""
    files = [ctx / "context.md"] + sorted((ctx / "personas").glob("*.md"))
    found = {schema_of(read_text_lenient(p)) for p in files if p.is_file()}
    found.discard(None)
    return sorted(found)[0] if len(found) == 1 else "0.1"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--store", default=None)
    ap.add_argument("--context", help="one context (default: every context in the store)")
    ap.add_argument("--to", default=SCHEMA_VERSION, help="target schema version (only %s)"
                                                         % SCHEMA_VERSION)
    ap.add_argument("--apply", action="store_true",
                    help="write the files (default: print the diff)")
    args = ap.parse_args(argv)
    # validated AFTER parse_args, so --help and an argparse usage error still work under an
    # unknown locale
    locale_err = check_locale()
    if locale_err:
        print(locale_err, file=sys.stderr)
        return 1

    if args.to != SCHEMA_VERSION:
        print("usage: --to %s is the only migration this release can produce (got %r). "
              "A store is never migrated down: read the older files, they still work."
              % (SCHEMA_VERSION, args.to), file=sys.stderr)
        return 1

    store = resolve_store(args.store)
    if not store.is_dir():
        print("usage: store not found: %s" % store, file=sys.stderr)
        return 1
    st = Store(store)
    if args.context:
        ctx = st.context(args.context)
        if not ctx.is_dir():
            print("usage: context not found: %s" % rel(ctx, store), file=sys.stderr)
            return 1
        contexts = [ctx]
    else:
        contexts = st.contexts()

    plans = [(ctx, planned_changes(ctx)) for ctx in contexts]
    refused = []
    for ctx, plan in plans:
        for path, old, new in plan:
            losses = content_loss(old, new)
            if losses:
                refused.append((path, losses))
    if refused:
        print("REFUSED: the migration would lose content.", file=sys.stderr)
        for path, losses in refused:
            print("  %s: %s" % (rel(path, store), "; ".join(losses)), file=sys.stderr)
        print("Nothing was written. Migrate these files by hand: a rule that rewrites a whole\n"
              "line cannot keep what a hand-written line carried in addition to the form it\n"
              "declared, and a script must not decide which of the two the author meant.",
              file=sys.stderr)
        return 2

    # What the declared-empty rule would not rewrite (E6): listed on every run, dry or not, so
    # the author sees the sentences a whole-bullet rule had to leave for them.
    for ctx in contexts:
        for p in Store(store).personas(ctx):
            for n, bullet in prose_empty_bullets(read_text_lenient(p)):
                print("left as prose: %s:%d: %s" % (rel(p, store), n, bullet[:120]))

    total = sum(len(plan) for _, plan in plans)
    if not total:
        print("nothing to migrate: every file already declares schema %s." % SCHEMA_VERSION)
        return 0

    if not args.apply:
        for ctx, plan in plans:
            for path, old, new in plan:
                name = rel(path, store)
                sys.stdout.writelines(difflib.unified_diff(
                    old.splitlines(keepends=True), new.splitlines(keepends=True),
                    fromfile=name, tofile=name + " (migrated)"))
                if not new.endswith("\n"):
                    print()
        print("\n%d file(s) would be migrated to schema %s, and the INDEX files regenerated."
              % (total, SCHEMA_VERSION))
        print("nothing written. Re-run with --apply after the user confirms.")
        return 0

    for ctx, plan in plans:
        if not plan:
            continue
        was = from_version(ctx)     # read before the write: afterwards every file says 0.2
        for path, _old, new in plan:
            atomic_write(path, new)
            print("written    %s" % rel(path, store))
        audit = st.audit(ctx)
        if audit.is_file():
            line = "%s | migrate %s -> %s | %d files changed" % (
                _today().isoformat(), was, SCHEMA_VERSION, len(plan))
            text = read_text_lenient(audit)
            atomic_write(audit, text.rstrip("\n") + "\n\n" + line + "\n")
            print("appended   %s: %s" % (rel(audit, store), line))
        else:
            print("no AUDIT.md in %s: the migration is recorded nowhere for this context."
                  % rel(ctx, store), file=sys.stderr)

    rc = reindex.main(["--store", str(store)]
                      + (["--context", args.context] if args.context else []))
    if rc:
        print("reindex exited %d after the migration: the files were written, the index was "
              "not fully rebuilt." % rc, file=sys.stderr)
    return 0


if __name__ == "__main__":
    print("deprecated: use beforehand.py migrate", file=sys.stderr)
    sys.exit(main())
